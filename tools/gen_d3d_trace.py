"""Generate src/android_d3d_trace.cpp: a call counter around every recompiled
function in Sonic's Direct3D zone, to map the XDK Direct3D at run time
(phase A of the native renderer, docs/native-renderer-map.md).

Each recompiled `sub_X` is a weak alias of `__imp__sub_X`; a strong `sub_X`
defined here wins for direct and indirect calls. The wrapper counts the call,
samples the return address (ctx.lr, set by the caller), and calls the original,
so the game behaves the same. The Swap function counts frames; reports are
written to $HOME/d3d_trace_<frame>.txt (HOME is the app's files folder).

usage: python tools/gen_d3d_trace.py   (built only with -DSONRAC_D3D_TRACE=ON)
"""
import re

ZONE_LO, ZONE_HI = 0x82CC0000, 0x82D10000
SWAP = 0x82CD9AE8
# Functions other files of src/ already define.
import glob as _glob
import os
SKIP = set()
for _path in _glob.glob('src/*.cpp'):
    if os.path.basename(_path) == 'android_d3d_trace.cpp':
        continue
    for _m in re.findall(r'REX_FUNC\(sub_([0-9A-Fa-f]{8})\)', open(_path, encoding='utf-8').read()):
        SKIP.add(int(_m, 16))

init = open('generated/sonicracingtransformed_init.cpp', encoding='utf-8').read()
funcs = sorted(set((int(a, 16), n) for a, n in re.findall(r'\{ 0x([0-9A-F]{8}), (\w+) \}', init)
                   if ZONE_LO <= int(a, 16) < ZONE_HI and n.startswith('sub_')
                   and int(a, 16) not in SKIP))

out = []
out.append('''// GENERATED by tools/gen_d3d_trace.py - do not edit.
// Call counter for Sonic's Direct3D zone (see tools/gen_d3d_trace.py).
#include <atomic>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <algorithm>
#include <vector>

#include <android/log.h>
#include <sys/uio.h>
#include <unistd.h>
#include <chrono>

#include "generated/sonicracingtransformed_init.h"

namespace {

constexpr int kCount = %d;
constexpr uint32_t kAddr[kCount] = {
%s
};

struct Slot {
  std::atomic<uint64_t> calls{0};
  // Calls with an argument pointing to a shader container (bytes 10 2A 11).
  std::atomic<uint32_t> container_args{0};
  std::atomic<uint32_t> container_reg{0};
  std::atomic<uint32_t> container_example{0};
  std::atomic<uint32_t> lr[4]{};
  std::atomic<uint32_t> lr_hits[4]{};
};
Slot g_slots[kCount];
std::atomic<uint32_t> g_frames{0};

inline bool PointsToContainer(uint8_t* base, uint32_t address) {
  if (address < 0x40000000u || address >= 0xFFFF0000u) return false;
  uint8_t bytes[3];
  iovec local{bytes, 3};
  iovec remote{base + address, 3};
  return process_vm_readv(getpid(), &local, 1, &remote, 1, 0) == 3 && bytes[0] == 0x10 &&
         bytes[1] == 0x2A && bytes[2] == 0x11;
}

inline void Hit(int i, uint32_t lr, PPCContext& ctx, uint8_t* base) {
  Slot& s = g_slots[i];
  const uint64_t n = s.calls.fetch_add(1, std::memory_order_relaxed);
  if (n < 4096) {
    const uint32_t args[6] = {ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, ctx.r7.u32, ctx.r8.u32};
    for (uint32_t a = 0; a < 6; ++a) {
      if (PointsToContainer(base, args[a])) {
        s.container_args.fetch_add(1, std::memory_order_relaxed);
        s.container_reg.store(3 + a, std::memory_order_relaxed);
        s.container_example.store(args[a], std::memory_order_relaxed);
        break;
      }
    }
  }
  if ((n & 15) != 0 && n > 64) return;  // sample callers: all of the first 64, then 1 in 16
  for (int k = 0; k < 4; ++k) {
    uint32_t cur = s.lr[k].load(std::memory_order_relaxed);
    if (cur == lr) { s.lr_hits[k].fetch_add(1, std::memory_order_relaxed); return; }
    if (cur == 0) {
      if (s.lr[k].compare_exchange_strong(cur, lr, std::memory_order_relaxed)) {
        s.lr_hits[k].fetch_add(1, std::memory_order_relaxed);
        return;
      }
      if (cur == lr) { s.lr_hits[k].fetch_add(1, std::memory_order_relaxed); return; }
    }
  }
}

void Report(uint32_t frame) {
  const char* home = std::getenv("HOME");
  char path[512];
  std::snprintf(path, sizeof(path), "%%s/d3d_trace_%%u.txt", home ? home : ".", frame);
  FILE* f = std::fopen(path, "w");
  if (!f) return;
  std::vector<int> order;
  for (int i = 0; i < kCount; ++i)
    if (g_slots[i].calls.load(std::memory_order_relaxed)) order.push_back(i);
  std::sort(order.begin(), order.end(), [](int a, int b) {
    return g_slots[a].calls.load() > g_slots[b].calls.load();
  });
  std::fprintf(f, "# frames=%%u functions_called=%%zu\\n# addr calls per_frame callers(lr:hits)\\n",
               frame, order.size());
  for (int i : order) {
    const uint64_t c = g_slots[i].calls.load();
    std::fprintf(f, "%%08X %%llu %%.2f", kAddr[i], (unsigned long long)c, double(c) / frame);
    if (g_slots[i].container_args.load())
      std::fprintf(f, " CONTAINER_ARG r%%u x%%u e.g. %%08X", g_slots[i].container_reg.load(),
                   g_slots[i].container_args.load(), g_slots[i].container_example.load());
    for (int k = 0; k < 4; ++k) {
      const uint32_t lr = g_slots[i].lr[k].load();
      if (lr) std::fprintf(f, " %%08X:%%u", lr, g_slots[i].lr_hits[k].load());
    }
    std::fprintf(f, "\\n");
  }
  std::fclose(f);
  __android_log_print(ANDROID_LOG_WARN, "SonRac", "d3d trace: %%s (%%zu functions)", path, order.size());
}

// Reports by time (the swap function may be hooked by another file).
const auto g_start = std::chrono::steady_clock::now();
std::atomic<uint32_t> g_reported{0};
void Frame() {
  static const uint32_t kAt[] = {30, 50, 70};
  uint32_t r = g_reported.load(std::memory_order_relaxed);
  if (r >= 3) return;
  const auto s = std::chrono::duration_cast<std::chrono::seconds>(
                     std::chrono::steady_clock::now() - g_start).count();
  const uint32_t at = kAt[r];
  if (uint32_t(s) >= at && g_reported.compare_exchange_strong(r, r + 1)) Report(at);
}

}  // namespace
''' % (len(funcs), ',\n'.join('  0x%08X' % a for a, _ in funcs)))

for i, (a, n) in enumerate(funcs):
    out.append(f'extern "C" REX_FUNC({n}) {{\n  Hit({i}, ctx.lr, ctx, base);\n  Frame();\n'
               f'  __imp__{n}(ctx, base);\n}}\n')

open('src/android_d3d_trace.cpp', 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(funcs), 'wrappers written to src/android_d3d_trace.cpp')
