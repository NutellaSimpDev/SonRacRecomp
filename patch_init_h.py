"""Bring generated/sonicracingtransformed_init.h's indirect-call dispatch up to the
ReXGlue 0.9.0 runtime used on Android. Run after every `rexglue codegen`.

The code is generated by the 0.7.5 CLI, whose REX_CALL_INDIRECT_FUNC jumps straight
through the per-module dispatch slot. An empty slot (a target the analyzer did not
register, or one outside the module, such as a kernel thunk) means a call to address
0. The 0.9.0 macro bounds-checks the target and falls back to
rex::runtime::ResolveIndirectFunction, which asks the global dispatcher and, failing
that, reports the guest address instead of crashing at pc 0.
"""
import re

PATH = 'generated/sonicracingtransformed_init.h'

NEW = r'''#define REX_CALL_FUNC(x) x(ctx, base)

#ifndef REX_THUNK_RESERVE_SIZE
#define REX_THUNK_RESERVE_SIZE 0x10000ull
#endif

#define REX_LOOKUP_FUNC(x, y) \
  (*(PPCFunc**)(x + REX_IMAGE_BASE + REX_IMAGE_SIZE + (u64(u32(y) - REX_CODE_BASE) * 2)))

// Patched by patch_init_h.py (ReXGlue 0.9.0 dispatch, see that script).
#define REX_CALL_INDIRECT_FUNC(x)                                                       \
  do {                                                                                  \
    uint32_t rex_indirect_target_ = (uint32_t)(x);                                      \
    PPCFunc* rex_indirect_func_;                                                        \
    if ((uint32_t)(rex_indirect_target_ - REX_CODE_BASE) <                              \
        REX_CODE_SIZE + REX_THUNK_RESERVE_SIZE) [[likely]] {                            \
      rex_indirect_func_ = REX_LOOKUP_FUNC(base, rex_indirect_target_);                 \
    } else {                                                                            \
      rex_indirect_func_ = nullptr;                                                     \
    }                                                                                   \
    if (!rex_indirect_func_) [[unlikely]] {                                             \
      ctx.last_indirect_target = rex_indirect_target_;                                  \
      rex_indirect_func_ = rex::runtime::ResolveIndirectFunction(rex_indirect_target_); \
    }                                                                                   \
    rex_indirect_func_(ctx, base);                                                      \
  } while (0)
'''

text = open(PATH, encoding='utf-8').read()
if 'Patched by patch_init_h.py' in text:
    print('already patched')
else:
    pattern = re.compile(r'#define REX_CALL_FUNC\(x\) x\(ctx, base\)\n.*?#endif\n', re.S)
    text, n = pattern.subn(lambda _: NEW, text, count=1)
    if n != 1:
        raise SystemExit('dispatch block not found in ' + PATH)
    open(PATH, 'w', encoding='utf-8', newline='\n').write(text)
    print('patched')
